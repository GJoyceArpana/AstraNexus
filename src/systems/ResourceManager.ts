// 5. RESOURCE SUMMARY & PROJECTIONS (For UI Dashboard)
// ============================================================================

/**
 * Returns net production/consumption deltas and alerts for Anusha's HUD.
 */
export function getResourceFlowSummary(state: OutpostGameState): ResourceFlowSummary {
    const powerGen = calculatePowerGeneration(state);
    const powerDrawn = calculatePowerDemand(state.activeModules);
    const powerSurplus = Number((powerGen.totalKw - powerDrawn).toFixed(2));
    const isPowerOverloaded = powerDrawn > powerGen.totalKw;

    const activeMods = new Set(state.activeModules);
    const loadoutEffects = calculateLoadoutEffects(state.loadout);
    const warnings: string[] = [];

    // If power is overloaded, modules fail to operate effectively
    const powerOperational = !isPowerOverloaded;

    // --- OXYGEN DELTA ---
    let netOxygen = -NASA_SPECS.OXYGEN_DAILY_CONSUMPTION;
    if (powerOperational && activeMods.has('life_support')) {
        netOxygen += NASA_SPECS.OXYGEN_DAILY_CONSUMPTION * NASA_SPECS.ECLSS_O2_RECOVERY_RATE;
    }
    if (powerOperational && activeMods.has('moxie')) {
        netOxygen += NASA_SPECS.MOXIE_O2_GENERATION_RATE;
    }
    // Pressure breach leakage penalty
    if (state.environment.internalPressureKpa < NASA_SPECS.SAFE_HAB_PRESSURE_MIN_KPA) {
        netOxygen -= 15.0; // Rapid atmospheric decompression leak
        warnings.push('HAB PRESSURE LOW: Atmospheric leakage active!');
    }

    // --- WATER DELTA ---
    let netWater = -NASA_SPECS.WATER_DAILY_CONSUMPTION;
    if (powerOperational && activeMods.has('life_support')) {
        netWater += NASA_SPECS.WATER_DAILY_CONSUMPTION * NASA_SPECS.ECLSS_WATER_RECOVERY_RATE;
    }
    if (powerOperational && activeMods.has('water_extractor')) {
        // Boosted by TRIDENT percussion drill tool
        const yieldMult = loadoutEffects.iceMiningYieldMultiplier;
        netWater += NASA_SPECS.ICE_MELTER_WATER_RATE * yieldMult;
    }
    // Greenhouse water consumption
    if (powerOperational && activeMods.has('led_greenhouse')) {
        netWater -= NASA_SPECS.GREENHOUSE_WATER_COST;
    }

    // --- FOOD DELTA ---
    let netFood = -NASA_SPECS.FOOD_DAILY_CONSUMPTION;
    if (powerOperational && activeMods.has('led_greenhouse')) {
        if (state.resources.water > 5) {
            netFood += NASA_SPECS.GREENHOUSE_FOOD_RATE;
        } else {
            warnings.push('GREENHOUSE STALLED: No water available for hydroponic crops!');
        }
    }

    // --- POWER WARNINGS ---
    if (isPowerOverloaded) {
        warnings.push(`POWER GRID OVERLOAD: Drawing ${powerDrawn} kW against ${powerGen.totalKw} kW available!`);
    } else if (powerSurplus < 1.0) {
        warnings.push('POWER CRITICAL: Near grid capacity limit.');
    }

    // --- RADIATION ---
    const dosePerSol = calculateRadiationExposure(
        state.environment,
        loadoutEffects.baseRadiationProtectionPercent
    );

    if (state.environment.solarFlareActive) {
        warnings.push('SOLAR PARTICLE EVENT ACTIVE: Seek regolith storm shelter immediately!');
    }

    return {
        netOxygenDelta: Number(netOxygen.toFixed(2)),
        netWaterDelta: Number(netWater.toFixed(2)),
        netFoodDelta: Number(netFood.toFixed(2)),
        powerAvailableKw: powerGen.totalKw,
        powerDrawnKw: powerDrawn,
        powerSurplusKw: powerSurplus,
        isPowerOverloaded,
        estimatedDosePerSolMsv: dosePerSol,
        activeWarnings: warnings,
    };
}

// ============================================================================
// 6. REAL-TIME TICK SIMULATION (Called by Scene update loop)
// ============================================================================

/**
 * Updates resources incrementally during live gameplay (e.g. driving, walking).
 * @param state Current game state
 * @param deltaSeconds Seconds elapsed in this frame/tick (e.g. 0.016 for 60fps)
 * @param timeScale Optional speed multiplier (default: 1.0 = 1 sec is ~0.1 Sol minutes)
 */
export function updateResourceTick(
    state: OutpostGameState,
    deltaSeconds: number,
    timeScale: number = 1.0
): OutpostGameState {
    if (state.status !== 'in_progress') {
        return state;
    }

    // Normalizing tick factor: 1 real second represents 1/60th of a Sol day
    const solFraction = (deltaSeconds * timeScale) / 60.0;
    const summary = getResourceFlowSummary(state);

    const prevRes = state.resources;
    let nextO2 = Math.min(100, Math.max(0, prevRes.oxygen + summary.netOxygenDelta * solFraction));
    let nextH2O = Math.min(100, Math.max(0, prevRes.water + summary.netWaterDelta * solFraction));
    let nextFood = Math.min(100, Math.max(0, prevRes.food + summary.netFoodDelta * solFraction));
    let nextRad = prevRes.radiationDose + summary.estimatedDosePerSolMsv * solFraction;
    let nextHealth = prevRes.crewHealth;
    let nextHull = prevRes.hullIntegrity;

    // --- CREW HEALTH PENALTIES & ABORT CHECKS ---
    let abortReason: AbortReason = state.abortReason;
    let missionStatus = state.status;

    // 1. Hypoxia
    if (nextO2 <= 0) {
        nextHealth -= 5.0 * solFraction; // Rapid degradation
        if (nextHealth <= 0) {
            missionStatus = 'emergency_abort';
            abortReason = 'HYPOXIA_OXYGEN_DEPLETED';
        }
    }

    // 2. Dehydration
    if (nextH2O <= 0) {
        nextHealth -= 3.5 * solFraction;
        if (nextHealth <= 0) {
            missionStatus = 'emergency_abort';
            abortReason = 'DEHYDRATION_WATER_DEPLETED';
        }
    }

    // 3. Starvation
    if (nextFood <= 0) {
        nextHealth -= 2.0 * solFraction;
        if (nextHealth <= 0) {
            missionStatus = 'emergency_abort';
            abortReason = 'STARVATION_FOOD_DEPLETED';
        }
    }

    // 4. Acute Radiation Sickness (ARS)
    if (nextRad >= NASA_SPECS.CAREER_RADIATION_LIMIT_MSV) {
        missionStatus = 'emergency_abort';
        abortReason = 'ACUTE_RADIATION_SICKNESS';
    }

    // 5. Thermal Freeze (if heaters unpowered during storm/night)
    if (summary.isPowerOverloaded && !state.activeModules.includes('thermal_heater')) {
        nextHealth -= 1.5 * solFraction;
        if (nextHealth <= 0) {
            missionStatus = 'emergency_abort';
            abortReason = 'THERMAL_FREEZE_POWER_LOSS';
        }
    }

    // 6. Perchlorate Toxicity
    if (state.environment.perchlorateLevel >= 85) {
        nextHealth -= 2.5 * solFraction;
        if (nextHealth <= 0) {
            missionStatus = 'emergency_abort';
            abortReason = 'PERCHLORATE_TOXICITY';
        }
    }

    const updatedResources: CoreResources = {
        oxygen: Number(nextO2.toFixed(2)),
        water: Number(nextH2O.toFixed(2)),
        food: Number(nextFood.toFixed(2)),
        powerAvailable: summary.powerAvailableKw,
        powerUsed: summary.powerDrawnKw,
        roverBattery: prevRes.roverBattery,
        hullIntegrity: Number(nextHull.toFixed(2)),
        crewHealth: Number(Math.max(0, nextHealth).toFixed(2)),
        radiationDose: Number(nextRad.toFixed(3)),
    };

    // Emit event bus notification for UI
    eventBus.emit('RESOURCE_UPDATED', updatedResources);

    if (missionStatus === 'emergency_abort') {
        eventBus.emit('EMERGENCY_ABORT', { reason: abortReason, state });
    }

    return {
        ...state,
        resources: updatedResources,
        status: missionStatus,
        abortReason,
    };
}

// ============================================================================
// 7. SOL DAY CONCLUSION & ACCUMULATION (Full Sol Advancement)
// ============================================================================

/**
 * Advances the game by 1 full Sol, calculating cumulative resource consumption,
 * solar radiation accumulation, and applying wear and tear.
 */
export function advanceSolResources(state: OutpostGameState): {
    state: OutpostGameState;
    summary: ResourceFlowSummary;
    solDoseMsv: number;
} {
    const summary = getResourceFlowSummary(state);
    const loadoutEffects = calculateLoadoutEffects(state.loadout);
    const solDoseMsv = summary.estimatedDosePerSolMsv;

    const prev = state.resources;
    const nextO2 = Math.min(100, Math.max(0, prev.oxygen + summary.netOxygenDelta));
    const nextH2O = Math.min(100, Math.max(0, prev.water + summary.netWaterDelta));
    const nextFood = Math.min(100, Math.max(0, prev.food + summary.netFoodDelta));
    const nextRad = Number((prev.radiationDose + solDoseMsv).toFixed(3));

    // Rover recharge from Bleep's solar cap:
    const roverRecharge = loadoutEffects.roverPassiveRechargePercent;
    const nextRoverBattery = Math.min(100, prev.roverBattery + roverRecharge);

    let nextHealth = prev.crewHealth;
    let abortReason: AbortReason = state.abortReason;
    let status = state.status;

    // Check critical failure conditions
    if (nextO2 <= 0) {
        status = 'emergency_abort';
        abortReason = 'HYPOXIA_OXYGEN_DEPLETED';
    } else if (nextH2O <= 0) {
        status = 'emergency_abort';
        abortReason = 'DEHYDRATION_WATER_DEPLETED';
    } else if (nextFood <= 0) {
        status = 'emergency_abort';
        abortReason = 'STARVATION_FOOD_DEPLETED';
    } else if (nextRad >= NASA_SPECS.CAREER_RADIATION_LIMIT_MSV) {
        status = 'emergency_abort';
        abortReason = 'ACUTE_RADIATION_SICKNESS';
    }

    const nextState: OutpostGameState = {
        ...state,
        resources: {
            ...prev,
            oxygen: Number(nextO2.toFixed(1)),
            water: Number(nextH2O.toFixed(1)),
            food: Number(nextFood.toFixed(1)),
            powerAvailable: summary.powerAvailableKw,
            powerUsed: summary.powerDrawnKw,
            roverBattery: nextRoverBattery,
            crewHealth: Number(nextHealth.toFixed(1)),
            radiationDose: nextRad,
        },
        status,
        abortReason,
        decisionLog: [
            ...state.decisionLog,
            `Sol ${state.currentSol} Complete: O2=${nextO2.toFixed(0)}%, H2O=${nextH2O.toFixed(0)}%, Food=${nextFood.toFixed(0)}%, Total Rad=${nextRad} mSv.`,
        ],
    };

    eventBus.emit('RESOURCE_UPDATED', nextState.resources);
    if (status === 'emergency_abort') {
        eventBus.emit('EMERGENCY_ABORT', { reason: abortReason, state: nextState });
    }

    return { state: nextState, summary, solDoseMsv };
}

// ============================================================================
// 8. ROVER BATTERY DISPATCH
// ============================================================================

/**
 * Consumes rover battery for physical operations (drilling, bulldozing, driving).
 */
export function consumeRoverBattery(
    state: OutpostGameState,
    percent: number
): { state: OutpostGameState; success: boolean } {
    if (state.resources.roverBattery < percent) {
        return { state, success: false };
    }

    const nextState: OutpostGameState = {
        ...state,
        resources: {
            ...state.resources,
            roverBattery: Math.max(0, state.resources.roverBattery - percent),
        },
    };

    eventBus.emit('RESOURCE_UPDATED', nextState.resources);
    return { state: nextState, success: true };
}

