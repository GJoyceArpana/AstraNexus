// ============================================================================
// 1. NASA SCIENTIFIC CONSTANTS & SPECIFICATIONS
// ============================================================================

/**
 * Real-world NASA baseline specifications:
 * - 0.84 kg O2 / astronaut / day (NASA HIDH)
 * - ~2.5 - 3.0 L H2O / astronaut / day
 * - ~2,500 - 3,000 kcal / astronaut / day
 * - GCR surface dose: ~0.67 mSv / Sol (NASA Curiosity RAD)
 * - NASA career safety limit: 500 mSv
 */
export const NASA_SPECS = {
    // Power Draw per Module (in Kilowatts - kW)
    MODULE_POWER_DRAW_KW: {
        life_support: 3.0,      // ECLSS air scrubbers, trace contaminant control
        moxie: 4.5,             // Solid Oxide Electrolysis (CO2 -> CO + O2 at 800°C)
        water_extractor: 3.5,   // Subsurface ice thermal melting & filtration pump
        led_greenhouse: 3.0,    // High-PAR photosynthetic LED grow lights (potatoes)
        comms_array: 2.0,       // High-gain X-band transmitter to Earth DSN
        thermal_heater: 2.5,    // Resistive heating against -60°C Martian night
    } as Record<ModuleId, number>,

    // Power Generation Baselines (kW)
    SOLAR_ARRAY_PEAK_KW: 15.0,
    KILOPOWER_REACTOR_KW: 10.0, // Fission Stirling reactor (steady 24/7)

    // Base Consumption Rates (per Sol without recycling or active generators)
    OXYGEN_DAILY_CONSUMPTION: 12.0,  // % of tank per Sol
    WATER_DAILY_CONSUMPTION: 10.0,   // % of tank per Sol
    FOOD_DAILY_CONSUMPTION: 8.0,     // % of storage per Sol

    // Production & Recycling Yields
    ECLSS_O2_RECOVERY_RATE: 0.75,     // 75% O2 loop closure
    ECLSS_WATER_RECOVERY_RATE: 0.90,  // 90% greywater recovery
    MOXIE_O2_GENERATION_RATE: 24.0,   // % O2 created per Sol when powered
    ICE_MELTER_WATER_RATE: 20.0,      // % water produced per Sol when powered
    GREENHOUSE_FOOD_RATE: 16.0,       // % food grown per Sol when powered
    GREENHOUSE_WATER_COST: 4.0,       // % water consumed by plants per Sol

    // Radiation Doses (mSv)
    BASE_SOL_RADIATION_MSV: 0.70,     // Ambient surface GCR per Sol
    SOLAR_FLARE_RADIATION_MSV: 85.0,  // Acute Coronal Mass Ejection dose
    CAREER_RADIATION_LIMIT_MSV: 500.0, // NASA astronaut career threshold

    // Leakage & Pressure Defaults
    SAFE_HAB_PRESSURE_MIN_KPA: 34.0,
} as const;

// ============================================================================
// 2. RESOURCE RATE PREVIEW INTERFACE (For Anusha's UI HUD)
// ============================================================================

export interface ResourceFlowSummary {
    netOxygenDelta: number;     // % change per Sol (e.g. +12% or -3%)
    netWaterDelta: number;      // % change per Sol
    netFoodDelta: number;       // % change per Sol
    powerAvailableKw: number;   // Total generation (Solar + Kilopower + Bleep)
    powerDrawnKw: number;       // Active modules load
    powerSurplusKw: number;     // Generation minus load
    isPowerOverloaded: boolean; // True if drawn > available
    estimatedDosePerSolMsv: number;
    activeWarnings: string[];
}

// ============================================================================
// 3. POWER SYSTEM CALCULATIONS
// ============================================================================

/**
 * Calculates total electrical power generated by solar arrays, Kilopower, and Bleep.
 */
export function calculatePowerGeneration(
    state: OutpostGameState
): { totalKw: number; solarKw: number; kilopowerKw: number; bleepKw: number } {
    const loadoutEffects = calculateLoadoutEffects(state.loadout);

    // Dust storm atmospheric opacity reduces solar output by up to 75%
    const dustPenalty = state.environment.dustStormIntensity * 0.75;
    const solarKw = Math.max(
        0,
        Number((NASA_SPECS.SOLAR_ARRAY_PEAK_KW * (1.0 - dustPenalty)).toFixed(2))
    );

    // Kilopower 10 kW nuclear fission reactor: immune to dust, weather, and night
    const kilopowerKw = state.environment.kilopowerActive
        ? NASA_SPECS.KILOPOWER_REACTOR_KW
        : 0;

    // Auxiliary power from Bleep's solar cap
    const bleepKw = loadoutEffects.passiveSolarPowerKw;

    const totalKw = Number((solarKw + kilopowerKw + bleepKw).toFixed(2));
    return { totalKw, solarKw, kilopowerKw, bleepKw };
}

/**
 * Calculates total electrical power drawn by currently toggled switchboard modules.
 */
export function calculatePowerDemand(activeModules: ModuleId[]): number {
    let totalDraw = 0;
    for (const modId of activeModules) {
        totalDraw += NASA_SPECS.MODULE_POWER_DRAW_KW[modId] || 0;
    }
    return Number(totalDraw.toFixed(2));
}

// ============================================================================
// 4. RADIATION & SHIELDING ATTENUATION
// ============================================================================

/**
 * Computes radiation dose (mSv) incurred based on regolith burial depth and solar flare activity.
 * Real NASA physics: 3.0 meters of compacted regolith reduces cosmic radiation by ~95%.
 */
export function calculateRadiationExposure(
    environment: OutpostEnvironment,
    loadoutBaseShieldingPercent: number
): number {
    // 1. Calculate regolith attenuation factor (0.0 = bare, 1.0 = full 3m shield)
    const regolithFactor = Math.min(1.0, environment.regolithThicknessM / 3.0);

    // Base shielding reduces exposure
    const baseProtection = loadoutBaseShieldingPercent / 100.0;
    const regolithProtection = regolithFactor * 0.80; // Up to 80% additional protection
    const totalAttenuation = Math.min(0.96, baseProtection + regolithProtection);
    const penetrationFactor = 1.0 - totalAttenuation;

    let dailyDoseMsv = NASA_SPECS.BASE_SOL_RADIATION_MSV * penetrationFactor;

    // If an intense solar flare (CME) is active (from Ganesh's DONKI endpoint):
    if (environment.solarFlareActive) {
        dailyDoseMsv += NASA_SPECS.SOLAR_FLARE_RADIATION_MSV * penetrationFactor;
    }

    return Number(dailyDoseMsv.toFixed(3));
}

